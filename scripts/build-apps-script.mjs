// The staging artifact is generated from the production core, never hand-edited.
import fs from 'node:fs';
import assert from 'node:assert/strict';

const root = new URL('../google-apps-script/', import.meta.url);
const core = fs.readFileSync(new URL('WalletSync.gs', root), 'utf8');
const views = fs.readFileSync(new URL('ProductionViews.gs', root), 'utf8');
assert.match(core, /const SPREADSHEET_ID = '[^']+';/);
assert.match(core, /const book = SpreadsheetApp.openById\(SPREADSHEET_ID\);/);
const stagingCore = core
  .replace(/const SPREADSHEET_ID = '[^']+';\n/, '')
  .replace('const book = SpreadsheetApp.openById(SPREADSHEET_ID);',
    "const id = PropertiesService.getScriptProperties().getProperty('STAGING_SPREADSHEET_ID');\n  if (!id) throw new Error('Missing STAGING_SPREADSHEET_ID');\n  const book = SpreadsheetApp.openById(id);");
const stagingViews = views.replaceAll('Production', 'Staging').replaceAll('production', 'staging').replaceAll('PRODUCTION_', 'STAGING_');
const aliases = `
// Compatibility names retained for tests and existing editor run menus.
function buildPeriods(platform, rows, targets) {
  return platform === 'wallet' ? buildWallet(rows, targets) : buildBusinessCanonical(rows, targets);
}
function saveView(platform, rows, targets) { return saveStagingView(platform, rows, targets); }
function readView(platform) { return readStagingView(platform); }
`;
const artifact = '// GENERATED by scripts/build-apps-script.mjs. Edit WalletSync.gs / ProductionViews.gs.\n' + stagingCore + '\n' + stagingViews + aliases;
const destination = new URL('WalletSync.staging.gs', root);
if (process.argv.includes('--check')) {
  assert.equal(fs.readFileSync(destination, 'utf8'), artifact, 'Staging Apps Script is out of date: run npm run apps-script:build');
  console.log('Apps Script staging/production source parity verified.');
} else {
  fs.writeFileSync(destination, artifact);
  console.log('Generated isolated staging Apps Script from the shared production core.');
}
